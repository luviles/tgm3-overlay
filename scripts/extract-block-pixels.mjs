/**
 * One-shot migration tool: extracts the 16x16 BGRA block sprite data from the
 * original C# BlockPixelData.cs and emits it as a compact base64 TS module.
 *
 * Usage: node scripts/extract-block-pixels.mjs <path-to-BlockPixelData.cs>
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = process.argv[2];
if (!SOURCE) {
  console.error("usage: node scripts/extract-block-pixels.mjs <path-to-BlockPixelData.cs>");
  process.exit(1);
}
const TARGET = join(here, "..", "src", "assets", "blockPixelData.ts");

const cs = readFileSync(SOURCE, "utf8");

const blockRe = /public static readonly byte\[\]\s+(\w+)\s*=\s*\{([\s\S]*?)\};/g;
const sprites = {};
let m;
while ((m = blockRe.exec(cs)) !== null) {
  const name = m[1];
  const numbers = m[2]
    .split(",")
    .map((s) => s.trim())
    .filter((s) => s.length > 0)
    .map((s) => parseInt(s, 10));
  if (numbers.length !== 16 * 16 * 4) {
    throw new Error(`${name}: expected 1024 bytes, got ${numbers.length}`);
  }
  sprites[name] = Buffer.from(numbers).toString("base64");
}

const names = Object.keys(sprites);
if (!names.includes("WBlock2") || !names.includes("CBlock2") || !names.includes("GBlock2")) {
  throw new Error(`missing expected sprite sets: ${names.join(", ")}`);
}

const out = `// AUTO-GENERATED by scripts/extract-block-pixels.mjs from the original
// Tgm3Visualizer Assets/BlockPixelData.cs (16x16 BGRA sprites, base64).
// Do not edit by hand.
//
// Sets: WBlock* = WORLD rule, CBlock* = CLASSIC rule, GBlock* = jewel blocks.
// Empty cells draw nothing — the card background shows through.

export const BLOCK_SIZE = 16;

export const SPRITES_B64: Record<string, string> = {
${names.map((n) => `  ${n}: ${JSON.stringify(sprites[n])},`).join("\n")}
};
`;

writeFileSync(TARGET, out);
console.log(`wrote ${TARGET} with ${names.length} sprites (${names.join(", ")})`);
